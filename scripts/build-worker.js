#!/usr/bin/env node
/*
 * Bundles the site into dist/_worker.js for Cloudflare Pages: the landing page and every
 * demos/<kind>/<client>/index.html are embedded as strings and served by a tiny worker.
 * (One file, so a deploy can't end up with missing pages.)
 *
 *   node scripts/build-worker.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const pages = { "/": "index.html" };
(function walk(dir) {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.join(dir, e.name);
    if (e.isDirectory()) walk(rel);
    else if (e.name === "index.html") pages["/" + dir.split(path.sep).join("/") + "/"] = rel;
  }
})("demos");

const files = {};
const routes = {};
Object.entries(pages).forEach(([route, file], i) => {
  const name = "P" + i;
  files[name] = fs.readFileSync(path.join(ROOT, file), "utf8");
  routes[route] = name;
  routes[route + "index.html"] = name;
});

const out = `// Generated by scripts/build-worker.js. Do not edit by hand.
${Object.entries(files).map(([n, html]) => `const ${n} = ${JSON.stringify(html)};`).join("\n")}
const PAGES = {
${Object.entries(routes).map(([r, n]) => `  ${JSON.stringify(r)}: ${n},`).join("\n")}
};
const HEADERS = {
  "content-type": "text/html; charset=utf-8",
  "cache-control": "public, max-age=300",
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
  "x-robots-tag": "noindex, nofollow",   // demos are shared by direct link only
};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    const path = url.pathname;
    if (!path.endsWith("/") && !path.endsWith(".html") && PAGES[path + "/"]) {
      return Response.redirect(url.origin + path + "/" + url.search, 301);
    }
    const body = PAGES[path];
    if (!body) return new Response("Not found", { status: 404, headers: { "content-type": "text/plain", "x-robots-tag": "noindex" } });
    return new Response(request.method === "HEAD" ? null : body, { headers: HEADERS });
  },
};
`;
fs.mkdirSync(path.join(ROOT, "dist"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "dist", "_worker.js"), out);
console.log(`dist/_worker.js: ${Object.keys(pages).length} pages, ${(out.length / 1024).toFixed(0)}KB`);
Object.keys(pages).forEach((r) => console.log("  " + r));
